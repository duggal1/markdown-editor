import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { performance } from 'node:perf_hooks';
import { countTokens, tokenize, countTokensCooperative, TOKENIZER_VERSION } from '../src/lib/tokenizer.ts';
import { scrambleDigits, SCRAMBLE_MS } from '../src/lib/tokenScramble.ts';
import { countAssetTokens, imageDimensions, imagePatchCount, imagePatches } from '../src/lib/imageTokens.ts';

assert.equal(TOKENIZER_VERSION, 'flow-lexical-v1');
const tokens = text => [...tokenize(text)].map(x=>x.value);
assert.deepEqual(tokens('Hello, world!'), ['Hello', ',', 'world', '!']);
assert.deepEqual(tokens('const x = "hello";'), ['const','x','=','"','hello','"',';']);
assert.deepEqual(tokens("don't"), ['don',"'",'t']);
assert.deepEqual(tokens('e\u0301 café देवनागरी'), ['e\u0301','café','देवनागरी']);
assert.deepEqual(tokens('你好世界'), ['你','好','世','界']);
assert.deepEqual(tokens('👩🏽‍💻 🇮🇳 1️⃣'), ['👩🏽‍💻','🇮🇳','1️⃣']);
assert.deepEqual(tokens('abc日本123'), ['abc','日','本','123']);
assert.equal(countTokens(' \r\n\t\u00a0'),0);
assert.equal(countTokens(''),0);
assert.equal(countTokens('',true),1);
// Actual encoded 1×1 PNG/GIF bytes, plus header fixtures for larger geometry.
const png = new Blob([Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l5sAAAAASUVORK5CYII=','base64')],{type:'image/png'});
const gif = new Blob([Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7','base64')],{type:'image/gif'});
assert.deepEqual(await imageDimensions(png),{width:1,height:1});
assert.deepEqual(await imageDimensions(gif),{width:1,height:1});
assert.equal(await countAssetTokens(png,true),1);
assert.equal(await countAssetTokens(undefined,false),0);
assert.equal(await countAssetTokens(new Blob(['not an image']),false),1);
assert.equal(await countAssetTokens(new Blob(['not an image']),true),1);
assert.equal(imagePatchCount(1024,768),768);
assert.equal(imagePatchCount(33,65),6);
const patches=[...imagePatches(33,65)];
assert.equal(patches.length,6);
assert.equal(patches.reduce((n,p)=>n+p.width*p.height,0),33*65);
assert.deepEqual(patches.at(-1),{x:32,y:64,width:1,height:1});
const header = new Uint8Array(await png.arrayBuffer());
const view = new DataView(header.buffer);
view.setUint32(16,1024);view.setUint32(20,768);
assert.equal(await countAssetTokens(new Blob([header],{type:'image/png'}),true),768);
const jpeg=new Blob([Uint8Array.from([255,216,255,192,0,11,8,0,65,0,33,1,1,17,0,255,217])],{type:'image/jpeg'});
assert.deepEqual(await imageDimensions(jpeg),{width:33,height:65});
assert.equal(await countAssetTokens(jpeg,true),6);
const bmp = new Uint8Array(54);bmp.set([66,77]);const bmpView=new DataView(bmp.buffer);
bmpView.setUint32(14,40,true);bmpView.setInt32(18,100,true);bmpView.setInt32(22,-100,true);
assert.equal(await countAssetTokens(new Blob([bmp],{type:'image/bmp'}),true),16);
const webp=new Uint8Array(30);webp.set(Buffer.from('RIFF'),0);webp.set(Buffer.from('WEBPVP8X'),8);webp[24]=63;webp[27]=95;
assert.equal(await countAssetTokens(new Blob([webp],{type:'image/webp'}),true),6);
assert.equal(countTokens('![cat](pic.png)'),9);
assert.deepEqual(tokens('<svg viewBox="0 0 24 24"/>'), ['<','svg','viewBox','=','"','0','0','24','24','"','/','>']);
assert.equal(countTokens('<svg viewBox="0 0 24 24"/>'),12);
for(const text of ['# Markdown\n\n**bold**', 'á 👩🏽‍💻 🏳️‍🌈', '<path d="M1 2L3 4"/>', 'a\u0000b', 'a\ud800b']) {
  const found = [...tokenize(text)];
  assert.equal(found.length,countTokens(text));
  assert.equal(found.map(t=>text.slice(t.start,t.end)).join(''),found.map(t=>t.value).join(''));
  let offset=0;
  for(const t of found){ assert.match(text.slice(offset,t.start),/^\s*$/u);offset=t.end; }
  assert.match(text.slice(offset),/^\s*$/u);
}
assert.equal(await countTokensCooperative('hello!',false,()=>false),2);
assert.equal(await countTokensCooperative('x '.repeat(10000),false,()=>true),null);
for(let p=0;p<1;p+=.05){const out=scrambleDigits('12,345',p,7);assert.match(out,/^\d{2},\d{3}$/);assert.equal(out.length,6);}
assert.notEqual(scrambleDigits('12,345',0,7),'12,345');
assert.equal(scrambleDigits('12,345',1,7),'12,345');
assert.ok(SCRAMBLE_MS<=200);
const fixture=('const x = "hello"; // code\n<svg viewBox="0 0 24 24"/>\n').repeat(20000);
const start=performance.now();
const count=countTokens(fixture);
const elapsed=performance.now()-start;
assert.equal(count, countTokens('const x = "hello"; // code\n<svg viewBox="0 0 24 24"/>\n')*20000);
console.log('Flow lexical benchmark:',JSON.stringify({characters:fixture.length,tokens:count,elapsedMs:Number(elapsed.toFixed(2))}));
