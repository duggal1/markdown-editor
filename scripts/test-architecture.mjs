import assert from 'node:assert/strict';
import {compileArchitecture,layoutArchitecture} from '../src/lib/architecture.ts';
const fence='\x60\x60\x60';
const graph=compileArchitecture(['## Repository structure',fence,'packages/','  catalog/         # canonical types','  retrieval/       # ranking','    index.ts','skills/','  SKILL.md',fence,'## Data flow','Client → API → DB','DB → Client'].join('\n'));
const node=label=>graph.nodes.find(n=>n.label===label);
assert.ok(node('catalog/'));
assert.equal(node('catalog/').detail,'canonical types');
assert.ok(graph.edges.some(e=>e.from===node('packages/').id&&e.to===node('catalog/').id&&e.kind==='contains'));
assert.ok(graph.edges.some(e=>e.from===node('Client').id&&e.to===node('API').id&&e.kind==='flow'));
assert.ok(graph.edges.some(e=>e.from===node('DB').id&&e.to===node('Client').id&&e.kind==='flow'));
assert.equal(graph.nodes.filter(n=>n.label==='Client').length,1);
const nested=compileArchitecture('## Services\n- API\n  - Auth\n- Storage');
assert.equal(nested.edges.filter(e=>e.kind==='contains').length,3);
assert.equal(compileArchitecture(fence+'python\nx = 1\n    print(x)\n'+fence).nodes.length,0);
assert.equal(compileArchitecture('ordinary prose only').nodes.length,0);
const large=compileArchitecture(Array.from({length:500},(_,i)=>'- Node '+i).join('\n'));
assert.equal(large.nodes.length,240);assert.equal(large.truncated,true);
const layout=layoutArchitecture(graph);assert.equal(layout.nodes.length,graph.nodes.length);
for(const n of layout.nodes) assert.ok(n.x>=0&&n.y>=0&&n.x+n.width<=layout.width&&n.y+n.height<=layout.height);
console.log('Architecture tree, nesting, source labels, explicit flows, cycles and bounded layout passed.');
