import assert from 'node:assert/strict';
import * as Y from 'yjs';
import { seedDocument, mergeDocument } from '../server/sync-crdt.js';
import { readFileSync } from 'node:fs';
const base=seedDocument('Tonight\n');
const a=new Y.Doc(), b=new Y.Doc();
Y.applyUpdate(a,base); Y.applyUpdate(b,base);
const initial=Y.encodeStateVector(a);
a.getText('markdown').insert(8,'Mac\n');
b.getText('markdown').insert(8,'Phone\n');
const ua=Y.encodeStateAsUpdate(a,initial), ub=Y.encodeStateAsUpdate(b,initial);
const first=mergeDocument(base,[ua,ub],initial);
const second=mergeDocument(base,[ub,ua,ua],initial);
assert.equal(first.markdown,second.markdown);
assert.equal(first.markdown.match(/Tonight/g).length,1);
assert.match(first.markdown,/Mac/); assert.match(first.markdown,/Phone/);
Y.applyUpdate(a,first.delta); Y.applyUpdate(b,second.delta);
assert.equal(a.getText('markdown').toString(),b.getText('markdown').toString());
const prior=Y.encodeStateVector(a);
a.getText('markdown').delete(0,7);
b.getText('markdown').insert(b.getText('markdown').length,'Offline\n');
const merged=mergeDocument(first.state,[Y.encodeStateAsUpdate(a,prior),Y.encodeStateAsUpdate(b,prior)],prior);
assert.doesNotMatch(merged.markdown,/Tonight/); assert.match(merged.markdown,/Offline/);
a.destroy(); b.destroy();
const dialog=readFileSync(new URL('../src/components/ShareDialog.tsx',import.meta.url),'utf8');
assert.match(dialog,/!markdownNote && !backedUp && <label/);
assert.doesNotMatch(dialog,/void enable\(\);\s*\n\s*\}/);
const shared=readFileSync(new URL('../src/components/SharedPage.tsx',import.meta.url),'utf8');
assert.match(shared,/If-None-Match/); assert.match(shared,/response.status === 304/);
assert.match(shared,/cause instanceof ShareUnavailable/);
console.log('CRDT concurrency, duplicate updates, offline merge and sharing integration passed.');
